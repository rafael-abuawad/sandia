import { cn } from "@/lib/utils";

export type AgentMascotMood = "idle" | "attentive" | "thinking";

export type AgentMascotHandle = {
  bounce: () => void;
  noticeTyping: () => void;
};

const TYPING_IDLE_MS = 1_000;

const BOUNCE_KEYFRAMES: Keyframe[] = [
  { transform: "scale(1, 1)" },
  { transform: "scale(1.04, 0.95)", offset: 0.35 },
  { transform: "scale(0.99, 1.02)", offset: 0.7 },
  { transform: "scale(1, 1)" },
];

